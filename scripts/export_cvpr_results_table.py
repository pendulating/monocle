#!/usr/bin/env python
"""Write the camera-ready validation-by-proxy table, without marimo.

`notebooks/cvpr/master/results_table.py` writes its files when you press a
button. That is fine for one look, but a paper table must be reproducible from
a command. This script runs the same calls and writes the same files.

It also holds the gate. Before it writes anything it checks 2 things:

1. The canonical registry matches the disk (`_canonical.verify_or_raise`).
2. Every case export is NEWER than the registry. An older export came from
   other runs, thus the table would mix 2 batteries. Run the case notebooks
   again, or pass `--allow-stale` when you know why.

Usage:
    python scripts/export_cvpr_results_table.py
    python scripts/export_cvpr_results_table.py --layers community_district nta

Warning: run it from the canonical venv, `.venv-mllmsci-vllm025cu129`.
"""

from __future__ import annotations

import argparse
import glob
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CVPR = REPO_ROOT / "notebooks" / "cvpr"
sys.path.insert(0, str(CVPR))

import pandas as pd  # noqa: E402

import _canonical as C  # noqa: E402
import _results_table as R  # noqa: E402

__version__ = "1.0.0"

OUT_DIR = CVPR / "master" / "outputs"
NOTEBOOK_VERSION = "1.0.0"


def registry_stamp() -> float:
    """The epoch time the registry was written."""
    blob = C.load()
    return time.mktime(time.strptime(blob["generated_at"], "%Y-%m-%dT%H:%M:%S"))


def stale_cases(stamp: float) -> list:
    """Name every case whose export is older than the registry."""
    out = []
    for case in R.CASES:
        pattern = str(CVPR / case["folder"] / "outputs"
                      / f"{case['prefix']}_aggregated_v*.parquet")
        hits = sorted(glob.glob(pattern))
        if not hits:
            out.append(f"{case['folder']}: no export at all")
            continue
        age = Path(hits[-1]).stat().st_mtime
        if age < stamp:
            out.append(f"{case['folder']}: export of "
                       f"{time.strftime('%Y-%m-%d %H:%M', time.localtime(age))} "
                       f"is older than the registry")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--layers", nargs="*", default=list(R.LAYER_KEY))
    ap.add_argument("--allow-stale", action="store_true",
                    help="write even when a case export predates the registry")
    args = ap.parse_args()

    print("[table] gate 1: the canonical registry")
    C.verify_or_raise()
    print(f"[table] {C.summary()}")

    print("[table] gate 2: every case export is newer than the registry")
    stale = stale_cases(registry_stamp())
    for s in stale:
        print(f"[table] STALE: {s}")
    if stale and not args.allow_stale:
        print("[table] refused. Run the case notebooks again:\n"
              "  marimo export html notebooks/cvpr/<case>/<case>_validation.py -o /dev/null")
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    banner = (f"% Canonical registry: {C.summary()}\n"
              f"% Written by scripts/export_cvpr_results_table.py v{__version__}.")

    written = []
    for layer in args.layers:
        results = R.build(layer=layer)
        if results.empty:
            print(f"[table] {layer}: no rows, skipped")
            continue
        stem = f"results_table_{layer}_v{NOTEBOOK_VERSION}"
        latex = R.to_latex(results, layer=layer)
        # The registry stamp goes INTO the file. A table in a paper must name
        # the data it came from, and a caption has no room for it.
        latex = latex.replace("% Generated by _results_table.py — do not edit by hand.",
                              "% Generated by _results_table.py — do not edit by hand.\n"
                              + banner, 1)
        (OUT_DIR / f"{stem}.tex").write_text(latex + "\n")
        R.to_display(results).to_csv(OUT_DIR / f"{stem}.csv", index=False)
        results.to_csv(OUT_DIR / f"{stem}_long.csv", index=False)
        R.wide(results).to_csv(OUT_DIR / f"{stem}_wide.csv")
        written += [f"{stem}.tex", f"{stem}.csv", f"{stem}_long.csv", f"{stem}_wide.csv"]
        n_rows = results.groupby(["case", "proxy"]).ngroups
        print(f"[table] {layer}: {n_rows} case-proxy rows, "
              f"{results['model'].nunique()} models")

    # The raw cross-model table carries no layer, thus it sits outside the loop.
    # It reads the run parquets of the registry, which gate 1 already checked.
    raw = R.raw_cross_model()
    if raw.empty:
        print("[table] raw cross-model: no rows, skipped")
    else:
        raw_stem = f"raw_cross_model_v{NOTEBOOK_VERSION}"
        raw_latex = R.raw_to_latex(raw).replace(
            "% Generated by _results_table.py — do not edit by hand.",
            "% Generated by _results_table.py — do not edit by hand.\n" + banner, 1)
        (OUT_DIR / f"{raw_stem}.tex").write_text(raw_latex + "\n")
        raw.to_csv(OUT_DIR / f"{raw_stem}.csv", index=False)
        written += [f"{raw_stem}.tex", f"{raw_stem}.csv"]
        print(f"[table] raw cross-model: {len(raw)} case rows, "
              f"{int(raw['n_pairs'].sum()):,} comparisons")

    pd.DataFrame(C.provenance_rows()).to_csv(
        OUT_DIR / f"canonical_runs_v{NOTEBOOK_VERSION}.csv", index=False)
    written.append(f"canonical_runs_v{NOTEBOOK_VERSION}.csv")

    print(f"[table] {len(written)} files -> {OUT_DIR.relative_to(REPO_ROOT)}")
    for w in written:
        print(f"          {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
