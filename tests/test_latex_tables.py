IC_ARM = "gemma_by_qwen27_v3"


def _ic_lift_frame() -> pd.DataFrame:
    """A small perspective lift frame: 3 keys over 3 cases."""
    rows = []
    for case, base in (("schools", 0.89), ("libraries", 0.86), ("restaurants", 0.82)):
        for key, lift in (("high_end", 0.07), ("functional", -0.30), ("a & b", 0.01)):
            sign = -1 if (key == "a & b" and case == "schools") else 1
            rows.append({"case": case, "key": key, "n": 100, "base_rate": base,
                         "lift": sign * lift, "pays": lift > 0.05,
                         "costs": lift < -0.05})
    return pd.DataFrame(rows)


def test_ic_sign_table_parses_and_escapes():
    tex = I.latex_sign_table(_ic_lift_frame(), IC_ARM, min_cases=3)
    assert L.check_table(tex) == []
    assert r"high\_end" in tex and r"a \& b" in tex
    assert "\\label{tab:ic-perspective-signs-gemma-by-qwen27-v3}" in tex
    assert "% Generated by _ic_v3.py" in tex
    # 2 of the 3 keys hold 1 sign; the 3rd changes sign in schools.
    assert tex.count(r"$\bullet$") == 2 + 1  # 2 rows and the caption
    assert "-.30" in tex and "+.07" in tex


def test_ic_perspective_ends_rows():
    ends = I.case_ends(_ic_lift_frame(), n=3)
    tex = I.latex_perspective_ends(ends, IC_ARM, n=3)
    assert L.check_table(tex) == []
    assert "Gemma-4-12B / Qwen3.8-27B" in tex
