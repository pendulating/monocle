def _trace_stats() -> pd.DataFrame:
    """A small long frame of `abstention_from_traces` over 4 arms."""
    from research.notebooks.cvpr import _extractions as X
    rows = []
    for arm in TC.v3_arms():
        spec = X.ARMS[arm]
        for case, auc in (("schools", 0.81), ("libraries", np.nan)):
            row = {"arm": arm, "role": TC.arm_role(arm), "judge": spec["judge"],
                   "extractor": spec["extractor"], "schema_version": "v3",
                   "case": case, "n_abstain": 30 if auc == auc else 3, "auc": auc}
            for col, _, _ in TC.MARKER_TABLE_COLUMNS:
                row.setdefault(col, auc)
            rows.append(row)
    return pd.DataFrame(rows)


def test_trace_abstention_auc_table():
    tex = TC.latex_abstention_auc(_trace_stats())
    assert L.check_table(tex) == []
    assert "\\label{tab:abstention-auc-arms}" in tex
    assert "Schools & 30 & .81 & .81 & 30 & .81 & .81 \\\\" in tex
    # A case under the floor prints dashes, not a number.
    assert "Libraries & 3 & -- & -- & 3 & -- & -- \\\\" in tex
    assert "Qwen3.8-27B" in tex and "Gemma-4-12B judge" in tex


def test_trace_abstention_markers_table():
    tex = TC.latex_abstention_markers(_trace_stats())
    assert L.check_table(tex) == []
    assert "\\label{tab:abstention-auc-markers}" in tex
    # Only the primary arms print, and a case without an AUC leaves.
    assert tex.count("\\quad Schools") == 2
    assert "Libraries" not in tex


def test_trace_tables_empty_frame():
    assert TC.latex_abstention_auc(pd.DataFrame()).startswith("%")
    assert TC.latex_abstention_markers(pd.DataFrame()).startswith("%")


def test_trace_export_latex_names(tmp_path):
    written = TC.export_latex(_trace_stats(), tmp_path, version="9.9.0")
    assert sorted(Path(p).name for p in written) == [
        "trace_channels_abstention_auc_v9.9.0.tex",
        "trace_channels_abstention_markers_v9.9.0.tex"]


