def test_same_image_pools_the_cases():
    rows = pd.DataFrame([
        {"case": "a", "extraction_class": "dimension", "entity": "image",
         "pair_n": 100, "pair_agree": 0.8, "chance_agree": 0.6},
        {"case": "b", "extraction_class": "dimension", "entity": "image",
         "pair_n": 300, "pair_agree": 0.6, "chance_agree": 0.5},
    ])
    tex = M.latex_same_image({ARM_G: rows})
    assert L.check_table(tex) == []
    # (0.8 * 100 + 0.6 * 300) / 400 = 0.65; chance (60 + 150) / 400 = 0.525.
    assert "Dimension, same image & .65 & [" in tex
    assert "& .53 & 400 \\\\" in tex


