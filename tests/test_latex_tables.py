def _gold_by_arm() -> pd.DataFrame:
    rows = []
    for arm, judge, ext in (("gemma_by_qwen27_v3", "gemma-4-12b", "qwen3.8-27b"),
                            ("gemma_by_gemma31_v3", "gemma-4-12b", "gemma-4-31b"),
                            ("qwen_by_gemma31_v3", "qwen3.5-9b", "gemma-4-31b")):
        for cls, f1 in (("dimension", 0.8), ("inference", 0.05), ("all", 0.5), ("any_class", 0.7)):
            rows.append({"arm": arm, "extractor": ext, "judge": judge, "cls": cls,
                         "n_human": 540, "n_pred": 1234, "matched": 10, "tasks": 6,
                         "precision": 0.9, "recall": 0.3, "f1": f1})
    return pd.DataFrame(rows)


def test_gold_positional_alignment_table():
    tex = G.latex_positional_alignment(_gold_by_arm())
    assert L.check_table(tex) == []
    assert "\\label{tab:gold-positional-alignment}" in tex
    # The primary arm comes first under its judge, and the qwen judge has 1 arm.
    assert "\\multicolumn{2}{c}{Gemma-4-12B traces} & \\multicolumn{1}{c}{Qwen3.5-9B traces}" in tex
    assert "Class & Qwen3.8-27B & Gemma-4-31B & Gemma-4-31B \\\\" in tex
    assert "visual evidence" not in tex and "dimension & .80 & .80 & .80" in tex
    assert "1{,}234" in tex and "12 gold traces" in tex


def test_gold_extractor_agreement_table():
    by_judge = pd.DataFrame([
        {"judge": j, "cls": c, "n_reference": 50, "n_other": 40, "matched": 30,
         "precision": 0.75, "recall": 0.6, "f1": 0.667}
        for j in ("qwen3.5-9b", "gemma-4-12b") for c in ("perspective", "all")])
    tex = G.latex_extractor_agreement(by_judge, traces={"gemma-4-12b": 140, "qwen3.5-9b": 120})
    assert L.check_table(tex) == []
    assert "Class & F1 & P & R & F1 & P & R \\\\" in tex
    assert tex.index("Gemma-4-12B traces") < tex.index("Qwen3.5-9B traces}")
    assert "perspective & .67 & .75 & .60" in tex and "120--140 shared traces" in tex


def test_gold_empty_frames_give_a_comment():
    assert G.latex_positional_alignment(pd.DataFrame()).startswith("%")
    assert G.latex_extractor_agreement(pd.DataFrame()).startswith("%")


def test_gold_rare_class_leaves_the_table():
    by_arm = _gold_by_arm()
    by_arm.loc[by_arm["cls"] == "inference", "n_human"] = 3
    tex = G.latex_positional_alignment(by_arm)
    assert "inference" not in tex and "dimension" in tex
    assert L.check_table(tex) == []


