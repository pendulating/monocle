@pytest.mark.parametrize("value, digits, signed, expected", [
    (0.934, 2, False, ".93"),
    (-0.012, 2, False, "-.01"),
    (-0.001, 2, False, ".00"),
    (1.204, 2, False, "1.20"),
    (0.05, 2, True, "+.05"),
    (-0.05, 2, True, "-.05"),
    (0.0004, 3, True, ".000"),
    (float("nan"), 2, False, "--"),
    (None, 2, False, "--"),
])
def test_fmt(value, digits, signed, expected):
    assert L.fmt(value, digits, signed=signed) == expected


def test_fmt_int_pct_ci():
    assert L.fmt_int(12345) == "12{,}345"
    assert L.fmt_int(np.nan) == "--"
    assert L.fmt_pct(0.426) == "43"
    assert L.fmt_ci(-0.04, 0.021) == "[-.04, .02]"
    assert L.fmt_ci(np.nan, 0.1) == "--"


def test_escape():
    assert L.escape("street_tree & 5% #1") == "street\\_tree \\& 5\\% \\#1"
    assert L.escape(None) == "--"


def test_labels():
    assert L.model_label("gemma-4-12b/instruct_thinking") == "Gemma-4-12B"
    assert L.arm_label("gemma_by_qwen27_v3") == "Gemma-4-12B / Qwen3.8-27B"
    assert "\\_" in L.arm_label("no_such_arm")


def _toy_table(body):
    head = L.group_header([("Gemma-4-12B", 2), ("Qwen3.5-9B", 2)])
    head.append(L.row(["Case", "a", "b", "a", "b"]))
    return L.table("_toy", "0.1.0", "\\textbf{A toy?} A toy table.", "tab:toy",
                   "lrrrr", head, body, resize=True, notes="A note.")


def test_table_wrapper_and_check():
    tex = _toy_table([L.row(["Road", ".10", "--", "-.20", ".30"])])
    assert tex.startswith("% Generated by _toy.py — do not edit by hand.")
    assert "% Written by research/notebooks/cvpr/_toy.py v0.1.0." in tex
    assert "\\label{tab:toy}" in tex and "\\resizebox{\\linewidth}{!}{%" in tex
    assert "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}" in tex
    assert L.check_table(tex) == []


def test_check_finds_problems():
    short = _toy_table([L.row(["Road", ".10", ".20"])])
    assert any("cells" in p for p in L.check_table(short))
    bare = _toy_table([L.row(["street_tree", "1", "2", "3", "4"])])
    assert any("unescaped _" in p for p in L.check_table(bare))
    math = _toy_table([L.row(["$\\kappa_{x}$", "1", "2", "3", "4"])])
    assert L.check_table(math) == []
    assert any("brace" in p for p in L.check_table(_toy_table(["{ & & & & \\\\"])))


def test_check_tabular_star():
    tex = ("\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrr}\n"
           "\\toprule\na & b & c \\\\\n\\bottomrule\n\\end{tabular*}")
    assert L.check_table(tex) == []


