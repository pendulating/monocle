def paradigm_order():
    d = pd.read_parquet("data/f11/f11_divergence.parquet")
    d = d[(d.unit == "U3") & (~d.raked)].set_index(["model", "case", "comparison"])
    print(sorted(set(i[2] for i in d.index)))
    rows = []
    for m, c in [("gemma-4-12b", "restaurant"), ("gemma-4-12b", "street"), ("qwen3.5-9b", "restaurant"), ("qwen3.5-9b", "street")]:
        v = d.loc[(m, c)]
        p = v.loc["paradigm"]
        rows.append(f"{dict(MODELS)[m]} & {c.title()} & {int(p['keys']):,} & {p.rho:.2f} [{p.rho_lo:.2f}, {p.rho_hi:.2f}] & "
                    f"{v.loc['R1_extractor'].rho:.2f} & {v.loc['R2_prompt'].rho:.2f} " + r"\\")
    write("paradigm-cue-order", "tab:paradigm-cue-order",
          r"\textbf{The cue order holds across paradigms.} Spearman $\rho$ (95\% bootstrap interval) between the net valence of each cue in the pairwise traces and in the evaluative single-image traces, with two reference values.",
          "llrrrr", [r"Model & Case & Cues & Paradigm $\rho$ & Extractor change & Prompt change \\"], rows,
          "Extractor change: the same pairwise traces, read by two extractors. Prompt change: descriptive against evaluative traces on the same images. A paradigm value near the extractor value says that the paradigm adds little.")


def trace_ses():
    d = pd.read_csv("research/notebooks/facct/figures/trace_ses/trace_ses_cells.csv")
    rows = []
    total = 0
    for key, name in [("valence", "Net valence of visual evidence"), ("social", "Net valence of social inferences"),
                      ("location", "Location inference"), ("uncertainty", "Uncertainty, in view")]:
        g = d[d.outcome == key].groupby("case").significant.agg(["sum", "size"])
        total += g["sum"].sum()
        rows.append(f"{name} & {g.loc['restaurant', 'sum']} of {g.loc['restaurant', 'size']} & "
                    f"{g.loc['street', 'sum']} of {g.loc['street', 'size']} " + r"\\")
    assert total == 124, total
    write("trace-ses-counts", "tab:trace-ses-counts",
          r"\textbf{Evaluative answers and area features.} Cells that pass, of Kendall $\tau$ tests of 6 models, 5 features, and the NTA and CD layers.",
          "lrr", [r"Outcome & Restaurant & Street \\"], rows,
          "Pass: Bonferroni $p<.05$.", width="0.6\\linewidth")


def h9():
    raw = pd.read_csv("research/figures/f9/h9_primary.csv")
    std = pd.read_csv("research/figures/f9/h9_standardized.csv")
    rows = []
    for key, name in MODELS:
        v = []
        for case in ("restaurant", "street"):
            for t in (raw, std):
                g = t[(t.model == key) & (t.case == case)]
                v.append(f"{int(g.h9.sum())} of {len(g)}")
        rows.append(f"{name} & " + " & ".join(v) + r" \\")
    tot = []
    for case in ("restaurant", "street"):
        for t in (raw, std):
            g = t[t.case == case]
            tot.append(f"{int(g.h9.sum())} of {len(g)}")
    rows += [r"\midrule", "All & " + " & ".join(tot) + r" \\"]
    assert raw.h9.sum() == 34 and std.h9.sum() == 23 and raw.flatter.sum() == 0 and std.flatter.sum() == 0
    write("h9-summary", "tab:h9-summary",
          r"\textbf{The evaluative task steepens the gradient.} Tests (of five ACS features) in which the slope of the per-image difference in net valence, evaluative minus descriptive, is significant with the sign of the descriptive gradient (Bonferroni over 60). Raw: net valence as measured. Standardized: each outcome divided by its standard deviation.",
          "lrrrr",
          [r" & \multicolumn{2}{c}{Restaurant} & \multicolumn{2}{c}{Street} \\",
           r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}", r"Model & Raw & Standardized & Raw & Standardized \\"],
          rows, "No test shows a flatter gradient under the evaluative prompt in either form.")


