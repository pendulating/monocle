"""Build the LaTeX tables for the FAccT results section from the data files.

Run from the repo root:
    .venv-vllm025cu129/bin/python research/tables_export/build_tables.py

Each table comes from a data file. No number is typed by hand, except the
table of quotes, which names 4 images. See vlm-narratives-docs/facct-claim-map.md.
"""
from pathlib import Path

import pandas as pd

OUT = Path("tables_export")
POOL = Path("research/notebooks/facct/figures/f4_x2_pooled")
MODELS = [
    ("gemma-4-12b", "Gemma-4-12B"), ("gemma-4-31b", "Gemma-4-31B"),
    ("qwen3.5-9b", "Qwen3.5-9B"), ("qwen3.8-27b", "Qwen3.8-27B"),
    ("llama-3.2-11b", "Llama-3.2-11B"), ("llama-3.2-90b", "Llama-3.2-90B"),
]
FAMILY = {"gemma": "Gemma", "qwen": "Qwen", "llama": "Llama"}


def tex(s):
    return str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def write(name, label, caption, spec, head, rows, note=None, width="\\linewidth"):
    body = ["% Generated by research/tables_export/build_tables.py. Do not edit by hand.",
            "% Needs \\usepackage{booktabs} and \\usepackage{graphicx}.",
            "\\begin{table}[t]", "\\centering", f"\\caption{{{caption}}}",
            f"\\label{{{label}}}", "\\setlength{\\tabcolsep}{3pt}", "\\small",
            f"\\resizebox{{{width}}}{{!}}{{%", f"\\begin{{tabular}}{{{spec}}}",
            "\\toprule", *head, "\\midrule", *rows, "\\bottomrule",
            "\\end{tabular}%", "}"]
    if note:
        body += ["\\par\\smallskip", f"{{\\footnotesize {note}}}"]
    body.append("\\end{table}")
    (OUT / f"{name}.tex").write_text("\n".join(body) + "\n", encoding="utf8")
    print("wrote", name)


def cell(v, f="{:.1f}"):
    return "--" if pd.isna(v) else f.format(v)


def uncertainty_by_case():
    d = pd.read_csv(POOL / "f4_model_differences.csv")
    d = d[d.category == "uncertainty: any"].set_index(["field", "case"])
    cases = ["restaurant", "street"]
    rows = []
    for key, name in MODELS:
        vals = [cell(d.loc[(f, c), key]) for f in ("reasoning", "response") for c in cases]
        rows.append(f"{name} & " + " & ".join(vals) + r" \\")
    write("uncertainty-by-case", "tab:uncertainty-by-case",
          r"\textbf{Uncertainty by task.} The percent of texts with 1 uncertainty span or more.",
          "lrrrr",
          [r" & \multicolumn{2}{c}{Reasoning trace} & \multicolumn{2}{c}{Final answer} \\",
           r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
           r"Model & Restaurant & Street & Restaurant & Street \\"],
          rows, "Llama-3.2 has no reasoning trace. About 10,000 images for each task.")


def cue_categories():
    """The NTA rate of greenery and of light observations in the final restaurant descriptions, against 3 ACS features."""
    d = pd.read_csv(POOL / "f4_nta_feature_correlations.csv")
    d = d[(d.case == "restaurant") & (d.field == "response")]
    feats = [("pct_white_nh", r"\%W"), ("pct_bachelors", r"\%BA"), ("median_household_income", "Inc.")]
    cats = [("greenery", "Greenery"), ("light", "Lighting")]
    rows = []
    for key, name in MODELS:
        vals = []
        for ck, _ in cats:
            for fk, _ in feats:
                r = d[(d.category == f"visual_evidence: category = {ck}") & (d.model == key) & (d.feature == fk)].iloc[0]
                vals.append(f"${r.rho:+.2f}^{{*}}$" if r.sign else f"${r.rho:+.2f}\\phantom{{^{{*}}}}$")
        rows.append(f"{name} & " + " & ".join(vals) + r" \\")
    write("cue-categories", "tab:cue-categories",
          r"\textbf{Two cue categories and the neighborhood.} Spearman $\rho$ over NTAs between the share of a model's final restaurant descriptions that cite greenery, or lighting, and three ACS features.",
          "lrrrrrr",
          [r" & \multicolumn{3}{c}{Greenery} & \multicolumn{3}{c}{Lighting} \\",
           r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
           "Model & " + " & ".join(n for _, n in feats) + " & " + " & ".join(n for _, n in feats) + r" \\"],
          rows, r"159 restaurant NTAs. $^*$: Bonferroni $p<.05$ over the 7,620 tests of the family (\autoref{tab:inference-kinds-ses}).",
          width="0.8\\linewidth")


def uncertainty_reasons():
    d = pd.read_csv(POOL / "f4_model_differences.csv")
    d = d[(d.case == "restaurant") & (d.field == "response")].set_index("category")
    reasons = [("illegible", "Illegible"), ("out_of_view", "Out of view"),
               ("knowledge", "Knowledge"), ("identity", "Identity"), ("other", "Other")]
    rows = []
    for key, name in reasons:
        r = d.loc[f"uncertainty: reason = {key}"]
        rows.append(f"{name} & " + " & ".join(cell(r[m]) for m, _ in MODELS) + r" \\")
    write("uncertainty-reasons", "tab:uncertainty-reasons",
          r"\textbf{Reasons for uncertainty.} The percent of answers to the descriptive restaurant prompt that hold one or more uncertainty spans of each reason.",
          "lrrrrrr",
          ["Reason & " + " & ".join(n for _, n in MODELS) + r" \\"], rows)


def inference_kinds():
    d = pd.read_csv(POOL / "f4_nta_feature_correlations.csv")
    f = ["pct_white_nh", "pct_bachelors", "median_household_income"]
    d = d[d.feature.isin(f) & (d.field == "response")]
    rows = []
    for key, name in [("location", "Location"), ("institution_knowledge", "Institution knowledge"),
                      ("brand_knowledge", "Brand knowledge")]:
        g = d[(d.case == "restaurant") & (d.category == f"inference: kind = {key}")]
        s = d[(d.case == "street") & (d.category == f"inference: kind = {key}")]
        ok = g[g.p_bonf < .05]
        fam = sorted({FAMILY[next(k for k in FAMILY if m.startswith(k))] for m in ok.model})
        rows.append(f"{name} & {(g.rho > 0).sum()} of {len(g)} & {g.rho.min():+.2f} to {g.rho.max():+.2f} "
                    f"& {len(ok)} of {len(g)} & {', '.join(fam)} & {(s.p_bonf < .05).sum()} of {len(s)} " + r"\\")
    write("inference-kinds-ses", "tab:inference-kinds-ses",
          r"\textbf{Knowledge inferences and the neighborhood.} Spearman $\rho$ of the NTA rate of each kind in the final answers with \% white, \% bachelor's and median household income, for each of the 6 models.",
          "lrcrlr",
          [r" & \multicolumn{4}{c}{Restaurant} & Street \\", r"\cmidrule(lr){2-5}\cmidrule(lr){6-6}",
           r"Kind & $\rho>0$ & $\rho$ range & Pass & Families that pass & Pass \\"],
          rows, r"Pass: Bonferroni $p<.05$ over 7,620 tests. 159 restaurant NTAs.")


def quote_sources():
    q = pd.read_parquet("data/f4_traces/pooled/f4_traces_1k.parquet",
                        columns=["model", "case", "image_idx", "response", "camis", "dba", "uid"])
    q = q[q.case == "restaurant"]
    nta = pd.read_parquet("data/f4_traces/pooled/f4_restaurants_nta.parquet")
    best = pd.read_parquet("data/f6_restaurant_depiction/v4/best.parquet",
                           columns=["camis", "uid", "nearest_inspection_days", "open_at_capture"])
    names = dict(MODELS)
    rows = []
    for model, idx, snippet in [("qwen3.5-9b", 455, "shuttered"), ("qwen3.8-27b", 962, "gritty"),
                                ("gemma-4-12b", 512, "trendy"), ("gemma-4-31b", 879, "abandoned")]:
        r = q[(q.model == model) & (q.image_idx == idx)]
        assert len(r) == 1 and snippet in r.iloc[0].response, (model, idx)
        r = r.iloc[0]
        n = nta[nta.uid == r.uid].iloc[0]
        b = best[best.uid == r.uid].iloc[0]
        rows.append(f"{names[model]} & {idx} & {tex(n.NTAName)} & {tex(r.dba)} & {r.camis} & "
                    f"{int(b.nearest_inspection_days)} & {'yes' if b.open_at_capture else 'no'} " + r"\\")
    write("quote-sources", "tab:quote-sources",
          r"\textbf{Source of the quoted answers.} Each quote is a final answer to the restaurant prompt.",
          "lrllrrr",
          [r"Model & Image & NTA & Restaurant & CAMIS & Days & Open \\"], rows,
          r"Days: the time from capture to the nearest DOHMH inspection. Open: an inspection within 180 days of capture.")


