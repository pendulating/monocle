"""Write the steering dose table of the paper (`tab:steering-dose`) from `research/figures/f10/steer/dose.csv` (F10.29 question 5).

Rows: model, prompt and layer of the 40-image dose run. Cells: the yes share with the shared aesthetic
direction added from the noun token onward, at each dose in units of sigma. The base column is the yes
share with no dose. The random control column gives the share of images that still get a yes or no
at 12 sigma. Output: `research/notebooks/facct/tables/f10_steer_dose.tex`, synced by paperkit.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from research.scripts.f10.hop_prompts import MODELS  # noqa: E402

__version__ = "1.1.0"
DOSE = ROOT / "research/figures/f10/steer/dose.csv"
OUT = ROOT / "research/notebooks/facct/tables/f10_steer_dose.tex"
NAMES = {"gemma-4-31b": "Gemma-4-31B", "qwen3.5-9b": "Qwen3.5-9B", "qwen3.6-27b": "Qwen3.6-27B"}
DOSES = (-48, -24, -12, 12, 24, 48)
PROMPTS = ("place cool", "place nice", "place ugly")
MIN_ANSWERED = 5


def main() -> None:
    d = pd.read_csv(DOSE)
    base = d[d.direction == "none"].set_index(["model", "prompt"]).yes_share
    aes = d[(d.direction == "aesthetic") & (d["where"] == "tail")]
    ctl = d[(d.direction == "control") & (d.alpha.abs() == 12)].groupby(["model", "prompt"]).answered.mean()
    lines = [
        "% Generated by research/scripts/f10/hop_steer_table.py (F10.29 question 5). Do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Steering with the shared aesthetic direction. The yes share of 40 images (one per neighborhood) when $\\alpha\\sigma$ times the direction is added to the residual stream from the noun token to the end of the prompt, at one layer. $\\sigma$ is the standard deviation, over the 591 images, of the projection of the residual on the direction. \\emph{Base}: no dose. \\emph{Control}: the share of images that still answer yes or no when a random unit vector is added at $\\pm12\\sigma$ at the first listed layer; at $\\pm24\\sigma$ and beyond, no Gemma-4-31B image answers under the control, while every Qwen image answers under every dose of either vector. Gemma-4-31B declines 'nice' on $.55$ and 'ugly' on $.95$ of these images with no dose, so its 'nice' and 'ugly' shares are over the images that answer. A dash: fewer than five images answer.}",
        "\\label{tab:steering-dose}",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\small",
        "\\begin{tabular}{llr" + "r" * (1 + len(DOSES)) + "r}",
        "\\toprule",
        " & & & \\multicolumn{" + str(1 + len(DOSES)) + "}{c}{yes share at $\\alpha$} & \\\\",
        "\\cmidrule(lr){4-" + str(3 + 1 + len(DOSES)) + "}",
        "Model & Prompt & Layer & " + " & ".join(["base"] + [f"${a:+d}$" for a in DOSES]) + " & Control \\\\",
        "\\midrule",
    ]
    for model in MODELS:
        if model not in aes.model.values:
            continue
        first_model = True
        for prompt in PROMPTS:
            s = aes[(aes.model == model) & (aes.prompt == prompt)]
            layers = sorted(s.layer.unique())
            for i, layer in enumerate(layers):
                row = s[s.layer == layer].set_index("alpha")
                cells = [f"{base[(model, prompt)]:.2f}"]
                for a in DOSES:
                    r = row.loc[float(a)] if float(a) in row.index else None
                    # A dash when fewer than MIN_ANSWERED images answer yes or no: the share is noise.
                    cells.append("--" if r is None or r.answered * r.n < MIN_ANSWERED else f"{r.yes_share:.2f}")
                name = NAMES[model] if first_model else ""
                adj = prompt.split()[1] if i == 0 else ""
                ctrl = f"{ctl[(model, prompt)]:.2f}" if i == 0 else ""
                lines.append(f"{name} & {adj} & {int(layer)} & " + " & ".join(cells) + f" & {ctrl} \\\\")
                first_model = False
            if prompt != PROMPTS[-1]:
                lines.append("\\addlinespace[2pt]")
        if model != MODELS[-1]:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    OUT.write_text("\n".join(lines))
    print(f"[f10.29] {OUT}: {len(lines)} lines")


if __name__ == "__main__":
    main()
