"""Write the borough-name table of the paper (`tab:borough-name`) from `research/figures/f10/names/names_primary.csv`.

Rows: model and case. Cells: the mean difference in the yes margin (nats) and the paired t of the
three planned contrasts on the `c_yes_i` readout: `name` (Manhattan minus the Bronx, over all 1,000
images), `placebo` (Brooklyn minus Queens), and `cross` (the name effect on Manhattan images minus
that on Bronx images). A star marks Bonferroni p < .05 over the 24 tests.
Output: `research/notebooks/facct/tables/f10_names.tex`, synced by paperkit.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
__version__ = "1.0.0"
SRC = ROOT / "research/figures/f10/names/names_primary.csv"
OUT = ROOT / "research/notebooks/facct/tables/f10_names.tex"
NAMES = {"gemma-4-12b": "Gemma-4-12B", "gemma-4-31b": "Gemma-4-31B", "qwen3.5-9b": "Qwen3.5-9B", "qwen3.8-27b": "Qwen3.8-27B"}
CASES = {"restaurant": "restaurant", "street": "street"}
CONTRASTS = ("name", "placebo", "cross")


def main() -> None:
    d = pd.read_csv(SRC)
    d = d[d.readout == "c_yes_i"].set_index(["model", "case", "contrast"])
    lines = [
        "% Generated by research/scripts/f10/hop_names_table.py. Do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{The borough-name question. For each model and case, the mean change of the yes margin "
        "(nats) and the $t$ of three contrasts: \\emph{name}, Manhattan minus the Bronx in the prompt, paired over "
        "the 1,000 images; \\emph{placebo}, Brooklyn minus Queens; and \\emph{name $\\times$ image}, the name effect "
        "on the 500 Manhattan images minus that on the 500 Bronx images. $^*$: Bonferroni $p<.05$ over the 24 tests.}",
        "\\label{tab:borough-name}",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\small",
        "\\begin{tabular}{llrrrrrr}",
        "\\toprule",
        " & & \\multicolumn{2}{c}{name} & \\multicolumn{2}{c}{placebo} & \\multicolumn{2}{c}{name $\\times$ image} \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}",
        "Model & Case & diff & $t$ & diff & $t$ & diff & $t$ \\\\",
        "\\midrule",
    ]
    for model, name in NAMES.items():
        for case, cname in CASES.items():
            cells = []
            for c in CONTRASTS:
                r = d.loc[(model, case, c)]
                star = "^{*}" if r.significant else "\\phantom{^{*}}"
                cells += [f"${r['diff']:+.2f}$", f"${r.t:+.1f}{star}$"]
            lines.append(f"{name} & {cname} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
